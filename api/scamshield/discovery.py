"""Model discovery: ``GET {BASE_URL}/models`` on Token Factory, rendered as docs/models.md."""

from __future__ import annotations

import re
from datetime import datetime, timezone

import httpx

TIER_HINTS = [
    ("MODEL_FAST", "Nemotron Nano", re.compile(r"nemotron.*nano|nano.*nemotron", re.I)),
    ("MODEL_MID", "Nemotron Super", re.compile(r"nemotron.*super|super.*nemotron", re.I)),
    ("MODEL_REASON", "Nemotron Ultra", re.compile(r"nemotron.*ultra|ultra.*nemotron", re.I)),
    ("MODEL_SAFETY", "Nemotron safety/guard", re.compile(r"nemotron.*(safety|guard)|(safety|guard).*nemotron", re.I)),
]


def fetch_models(base_url: str, api_key: str, *, transport: httpx.BaseTransport | None = None) -> list[dict]:
    with httpx.Client(
        base_url=base_url.rstrip("/") + "/", headers={"Authorization": f"Bearer {api_key}"}, timeout=30.0, transport=transport
    ) as client:
        resp = client.get("models")
        resp.raise_for_status()
        data = resp.json()
    models = data.get("data", data) if isinstance(data, dict) else data
    return sorted((m for m in models if isinstance(m, dict) and m.get("id")), key=lambda m: m["id"])


def suggest(models: list[dict]) -> list[tuple[str, str, list[str]]]:
    """(env var, wanted family, matching ids) for each routing tier. Matching is by name only: confirm by hand."""
    ids = [m["id"] for m in models]
    return [(env, family, [i for i in ids if rx.search(i)]) for env, family, rx in TIER_HINTS]


def render_markdown(models: list[dict], base_url: str, *, now: datetime | None = None) -> str:
    stamp = (now or datetime.now(timezone.utc)).strftime("%Y-%m-%d %H:%M UTC")
    out = [
        "# Token Factory models",
        "",
        f"Generated by `scripts/discover_models.py` from `GET {base_url.rstrip('/')}/models` on {stamp}.",
        "",
        "## Routing candidates",
        "",
        "| Env var | Wanted | Matching model ids |",
        "|---|---|---|",
    ]
    for env, family, matches in suggest(models):
        out.append(f"| `{env}` | {family} | {', '.join(f'`{m}`' for m in matches) or '_none listed_'} |")
    out += ["", f"## All models ({len(models)})", "", "| id | owned_by |", "|---|---|"]
    out += [f"| `{m['id']}` | {m.get('owned_by', '')} |" for m in models]
    out.append("")
    return "\n".join(out)
